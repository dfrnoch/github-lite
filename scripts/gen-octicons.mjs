// Generates src/icons/octicons.ts from @primer/octicons: one named export per
// icon (camelCase + "Icon"), so the bundler tree-shakes unused icons away.
// Run: node scripts/gen-octicons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const data = JSON.parse(readFileSync(require.resolve('@primer/octicons/build/data.json'), 'utf8'));

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const paths = (svg) => [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);

let out = `// Generated by scripts/gen-octicons.mjs from @primer/octicons. Do not edit.
export interface OcticonData {
  /** Path data per design size (16 and/or 24). */
  readonly sizes: { readonly [height: number]: { readonly width: number; readonly d: readonly string[] } };
}
`;
for (const name of Object.keys(data).sort()) {
  const sizes = {};
  for (const [h, v] of Object.entries(data[name].heights)) {
    sizes[h] = { width: v.width, d: paths(v.path) };
  }
  out += `export const ${camel(name)}Icon: OcticonData = ${JSON.stringify({ sizes })};\n`;
}
writeFileSync(new URL('../src/icons/octicons.ts', import.meta.url), out);
console.log(`wrote ${Object.keys(data).length} icons`);
