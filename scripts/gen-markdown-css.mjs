// Generates src/styles/markdown.css from github-markdown-css with every
// hard-coded color replaced by the Primer token that holds it, so rendered
// markdown follows the active Primer theme (light, dark, dimmed, high
// contrast, colorblind) instead of the OS setting.
//
// A token is accepted only if it matches the color at the same position in
// BOTH the light and the dark stylesheet of github-markdown-css, which makes
// the mapping semantic rather than a lucky hex coincidence.
// Run: bun scripts/gen-markdown-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const read = (spec) => readFileSync(require.resolve(spec), 'utf8');
const lightMd = read('github-markdown-css/github-markdown-light.css');
const darkMd = read('github-markdown-css/github-markdown-dark.css');

function primer(name) {
  const css = read(`@primer/primitives/dist/css/functional/themes/${name}.css`);
  const vars = {};
  for (const m of css.matchAll(/(--[a-zA-Z0-9-]+):\s*([^;]+);/g)) vars[m[1]] ??= m[2].trim();
  const resolve = (k, depth = 0) => {
    const v = vars[k];
    if (!v || depth > 8) return v;
    const ref = v.match(/^var\((--[^)]+)\)$/);
    return ref ? resolve(ref[1], depth + 1) : v.toLowerCase();
  };
  return { names: Object.keys(vars), resolve };
}
const L = primer('light');
const D = primer('dark');

const COLOR = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g;
const norm = (c) => {
  c = c.toLowerCase().replace(/\s+/g, '');
  const rgba = c.match(/^rgba?\((\d+),(\d+),(\d+)(?:,([\d.]+))?\)$/);
  if (rgba) {
    const [r, g, b] = rgba.slice(1, 4).map((x) => Number(x).toString(16).padStart(2, '0'));
    const a = rgba[4] === undefined ? '' : Math.round(Number(rgba[4]) * 255).toString(16).padStart(2, '0');
    return `#${r}${g}${b}${a === 'ff' ? '' : a}`;
  }
  if (/^#[0-9a-f]{3}$/.test(c)) return `#${c.slice(1).replace(/./g, '$&$&')}`;
  return c;
};

// Prefer tokens whose family suits the CSS property being set.
const prefer = (prop) =>
  /^color$/.test(prop) ? ['--fgColor-', '--color-prettylights-', '--prettylights-']
  : /background/.test(prop) ? ['--bgColor-', '--color-prettylights-', '--prettylights-']
  : /border|outline|box-shadow/.test(prop) ? ['--borderColor-']
  : [];

const lightColors = [...lightMd.matchAll(COLOR)];
const darkColors = [...darkMd.matchAll(COLOR)];
if (lightColors.length !== darkColors.length) throw new Error('light/dark stylesheets differ in structure');

let out = '';
let last = 0;
let mapped = 0;
const kept = [];
lightColors.forEach((m, i) => {
  const lightHex = norm(m[0]);
  const darkHex = norm(darkColors[i][0]);
  const before = lightMd.slice(0, m.index);
  const prop = before.slice(before.lastIndexOf('\n') + 1).trim().split(':')[0];
  const candidates = L.names.filter(
    (n) => !n.startsWith('--base-') && L.resolve(n) === lightHex && D.resolve(n) === darkHex,
  );
  const order = prefer(prop);
  candidates.sort((a, b) => {
    const rank = (n) => {
      const i = order.findIndex((p) => n.startsWith(p));
      return i === -1 ? order.length : i;
    };
    return rank(a) - rank(b);
  });
  out += lightMd.slice(last, m.index);
  if (candidates[0]) {
    out += `var(${candidates[0]})`;
    mapped++;
  } else {
    // No token is right in both themes (e.g. a transparent/neutral value): keep it.
    out += m[0];
    if (lightHex !== darkHex) kept.push(`${prop}: ${lightHex} / ${darkHex}`);
  }
  last = m.index + m[0].length;
});
out += lightMd.slice(last);

out = out
  .replace('/*light */\n', '')
  .replace(/\n  color-scheme: light;/, '');

writeFileSync(
  new URL('../src/styles/markdown.css', import.meta.url),
  `/* Generated by scripts/gen-markdown-css.mjs from github-markdown-css. Do not edit. */\n${out}`,
);
console.log(`mapped ${mapped}/${lightColors.length} colors to Primer tokens`);
if (kept.length) console.log('left as-is (differ between themes, no token):\n  ' + kept.join('\n  '));
